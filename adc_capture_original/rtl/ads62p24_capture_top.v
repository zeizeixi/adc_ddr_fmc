`timescale 1ns/1ps
`default_nettype none
// Receives the ADC output clock at a clock-capable FPGA pin; BUFG is inside.
// i_sys_rst and i_ui_rst must assert at startup. No automatic acquisition.
// ONE SHOT: pulse i_start_sys while o_ready_sys=1; start is latched across CDC.
// This module supplies a FWFT valid/ready stream in the MIG ui_clk domain.
module ads62p24_capture_top #(
    parameter integer CAPTURE_SAMPLES = 20000000,
    parameter integer TEST_RAMP = 0,
    parameter integer CFG_POWER_WAIT = 100000,
    parameter integer CFG_RESET_HIGH = 100,
    parameter integer CFG_RESET_WAIT = 100,
    parameter integer CFG_SETTLE = 10000
)(
    input wire i_sys_clk_100m, input wire i_sys_rst,
    input wire i_adc_clk_out,
    input wire [13:2] i_adc_da, input wire [13:2] i_adc_db,
    output wire o_adc_reset, output wire o_adc_cs_n,
    output wire o_adc_sck, output wire o_adc_sdi, output wire [2:0] o_adc_ctrl,
    input wire i_ui_clk, input wire i_ui_rst, input wire i_mig_calib_done,
    input wire i_start_sys,
    output wire o_ready_sys, output wire o_cfg_done_sys,
    output wire o_capture_done_sys, output wire o_overflow_sys,
    output wire o_capture_busy_sys,
    output wire [255:0] o_data_ui, output wire o_valid_ui, input wire i_ready_ui,
    output wire o_adc_clk_debug,
    output wire [31:0] o_sample_count_adc
);
    wire adc_clk;
    BUFG u_adc_bufg(.I(i_adc_clk_out),.O(adc_clk));
    assign o_adc_clk_debug = adc_clk;
    wire arst = i_sys_rst | i_ui_rst;
    wire sys_rst, adc_rst, ui_rst;
    reset_sync u_sys_reset(.clk(i_sys_clk_100m),.arst(arst),.rst(sys_rst));
    wire cfg_done;
    ads62p24_init #(
        .TEST_RAMP(TEST_RAMP), .POWER_WAIT_CYCLES(CFG_POWER_WAIT),
        .RESET_HIGH_CYCLES(CFG_RESET_HIGH), .RESET_WAIT_CYCLES(CFG_RESET_WAIT),
        .SETTLE_CYCLES(CFG_SETTLE)
    ) u_init (
        .clk(i_sys_clk_100m),.rst(sys_rst),.adc_reset(o_adc_reset),
        .adc_cs_n(o_adc_cs_n),.adc_sck(o_adc_sck),.adc_sdi(o_adc_sdi),
        .adc_ctrl(o_adc_ctrl),.done(cfg_done)
    );
    assign o_cfg_done_sys = cfg_done;
    wire fifo_arst = arst | !cfg_done;
    reset_sync u_adc_reset(.clk(adc_clk),.arst(fifo_arst),.rst(adc_rst));
    reset_sync u_ui_reset(.clk(i_ui_clk),.arst(fifo_arst),.rst(ui_rst));
    wire full, empty, wr_busy, rd_busy;
    wire full_sys, wr_busy_sys, rd_busy_sys, calib_sys;
    level_sync #(.RESET_VALUE(1'b1)) u_wbusy(.clk(i_sys_clk_100m),.rst(sys_rst),.async_in(wr_busy),.sync_out(wr_busy_sys));
    level_sync #(.RESET_VALUE(1'b1)) u_rbusy(.clk(i_sys_clk_100m),.rst(sys_rst),.async_in(rd_busy),.sync_out(rd_busy_sys));
    level_sync #(.RESET_VALUE(1'b1)) u_full(.clk(i_sys_clk_100m),.rst(sys_rst),.async_in(full),.sync_out(full_sys));
    level_sync u_calib(.clk(i_sys_clk_100m),.rst(sys_rst),.async_in(i_mig_calib_done),.sync_out(calib_sys));
    reg start_latched;
    assign o_ready_sys = cfg_done && calib_sys && !wr_busy_sys && !rd_busy_sys &&
                         !full_sys && !start_latched && !sys_rst;
    always @(posedge i_sys_clk_100m) begin
        if (sys_rst) start_latched <= 0;
        else if (i_start_sys && o_ready_sys) start_latched <= 1;
    end
    wire start_adc, cap_busy, cap_done, cap_overflow;
    level_sync u_start(.clk(adc_clk),.rst(adc_rst),.async_in(start_latched),.sync_out(start_adc));
    wire [255:0] pack_data;
    wire pack_valid;
    wire pack_ready = !full && !wr_busy && !adc_rst;
    ads62p24_pack256 #(.CAPTURE_SAMPLES(CAPTURE_SAMPLES)) u_pack (
        .adc_clk(adc_clk),.rst(adc_rst),.start(start_adc && !wr_busy),
        .adc_a(i_adc_da),.adc_b(i_adc_db),
        .out_data(pack_data),.out_valid(pack_valid),.out_ready(pack_ready),
        .busy(cap_busy),.done(cap_done),.overflow(cap_overflow),
        .sample_count(o_sample_count_adc)
    );
    wire pop = o_valid_ui && i_ready_ui;
    // Generated by scripts/create_fifo_ip.tcl. Do not substitute a Standard FIFO.
    adc_fifo_256x512 u_fifo (
        .rst(fifo_arst),.wr_clk(adc_clk),.rd_clk(i_ui_clk),
        .din(pack_data),.wr_en(pack_valid && pack_ready),.rd_en(pop),
        .dout(o_data_ui),.full(full),.empty(empty),
        .wr_rst_busy(wr_busy),.rd_rst_busy(rd_busy)
    );
    assign o_valid_ui = !empty && !rd_busy && !ui_rst && i_mig_calib_done;
    level_sync u_done(.clk(i_sys_clk_100m),.rst(sys_rst),.async_in(cap_done),.sync_out(o_capture_done_sys));
    level_sync u_error(.clk(i_sys_clk_100m),.rst(sys_rst),.async_in(cap_overflow),.sync_out(o_overflow_sys));
    // Covers request transit as well as ADC-side acquisition and final FIFO push.
    assign o_capture_busy_sys = start_latched && !o_capture_done_sys && !o_overflow_sys;
endmodule
`default_nettype wire
